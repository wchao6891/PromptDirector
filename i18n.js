let activeLocale = "zh-CN";

export async function initializeUi(preferencesValue) {
  const stored = preferencesValue || (await chrome.storage.local.get("uiPreferences")).uiPreferences;
  const preferences = normalizeUiPreferences(stored);
  activeLocale = resolveLocale(preferences, chrome.i18n.getUILanguage());
  document.documentElement.lang = activeLocale;
  document.documentElement.dataset.theme = preferences.theme;
  document.documentElement.dataset.resolvedTheme = preferences.theme === "system"
    ? (globalThis.matchMedia?.("(prefers-color-scheme: dark)").matches ? "dark" : "light")
    : preferences.theme;
  document.documentElement.dataset.motion = preferences.motion;
  document.documentElement.style.backgroundColor = "var(--ui-browser)";
  document.documentElement.style.colorScheme = document.documentElement.dataset.resolvedTheme;
  if (document.body) {
    document.body.style.backgroundColor = "var(--ui-page)";
    document.body.style.color = "var(--ui-text)";
    document.body.style.colorScheme = document.documentElement.dataset.resolvedTheme;
  }
  localStorage.setItem("promptDirectorTheme", preferences.theme);
  localStorage.setItem("promptDirectorMotion", preferences.motion);
  applyDocumentTranslations(document);
  return preferences;
}

export function currentLocale() {
  return activeLocale;
}

export function hasEnglishTranslation(source) {
  return Boolean(EN[source]);
}

export function t(source, values = {}) {
  const template = activeLocale === "en" ? (EN[source] || source) : source;
  return Object.entries(values).reduce(
    (text, [key, value]) => text.replaceAll(`{${key}}`, String(value)),
    template
  );
}

export function translateForLocale(source, locale) {
  return locale === "en" ? (EN[source] || source) : source;
}

export function applyDocumentTranslations(root = document) {
  for (const item of root.querySelectorAll("[data-i18n]")) item.textContent = t(item.dataset.i18n);
  for (const item of root.querySelectorAll("[data-i18n-placeholder]")) item.placeholder = t(item.dataset.i18nPlaceholder);
  for (const item of root.querySelectorAll("[data-i18n-aria-label]")) item.setAttribute("aria-label", t(item.dataset.i18nAriaLabel));
  for (const item of root.querySelectorAll("[data-i18n-title]:not(html)")) item.title = t(item.dataset.i18nTitle);
  document.documentElement.removeAttribute("title");
  document.title = t(document.documentElement.dataset.i18nTitle || document.title);
}


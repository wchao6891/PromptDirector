export async function updateUiPreferences(next) {
  const response = await chrome.runtime.sendMessage({ type: "UPDATE_UI_PREFERENCES", preferences: next });
  if (!response?.ok) throw new Error(response?.message || t("操作失败"));
  localStorage.setItem("promptDirectorTheme", response.uiPreferences.theme);
  localStorage.setItem("promptDirectorMotion", response.uiPreferences.motion);
  return response.uiPreferences;
}

